"""Write notes/reading-list-skin.md: the works closest to Peter's diagnosis.

Lists every catalog entry with focus == "primary" (myoepithelial carcinoma of
the skin, and malignant mixed tumour of the skin), newest first, with how to
get each one.

    python harvest/reading_list.py
"""

import collections
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import CATALOG, FULLTEXT, ROOT, log, read_jsonl  # noqa: E402

OUT = ROOT / "notes" / "reading-list-skin.md"


def link(rec):
    if rec["pmid"]:
        return "https://pubmed.ncbi.nlm.nih.gov/%s/" % rec["pmid"]
    if rec["doi"]:
        return "https://doi.org/%s" % rec["doi"]
    return ""


def access(rec, have):
    if rec["pmcid"] in have:
        return "full text in repo (%s)" % rec["pmcid"]
    if rec["is_oa"]:
        return "open access, not yet downloaded"
    return "not open access"


def main():
    papers = read_jsonl(CATALOG / "papers.jsonl")
    have = {p.name[:-7] for p in FULLTEXT.glob("PMC*.xml.gz")}
    primary = [p for p in papers if p["focus"] == "primary"]
    secondary = [p for p in papers if p["focus"] == "secondary"]
    primary.sort(key=lambda p: (-(p["year"] or 0), p["id"]))
    tally = collections.Counter(access(p, have).split(" (")[0] for p in primary)

    lines = [
        "# Reading list: skin and adnexal myoepithelial carcinoma",
        "",
        "Generated by `harvest/reading_list.py` from the catalog. Do not edit by hand.",
        "",
        "These are the works closest to Peter's diagnosis:",
        "myoepithelial carcinoma where the title or abstract places it in the skin, and",
        "malignant mixed tumour of the skin (malignant chondroid syringoma), the closely",
        "related diagnosis. Selection is by keyword, so expect some entries that do not",
        "belong and some that are missing.",
        "",
        "- %d works in this list. %d are flagged as case reports."
        % (len(primary), sum(p["is_case_report"] for p in primary)),
    ]
    for label, n in tally.most_common():
        lines.append("- %s: %d" % (label.capitalize(), n))
    lines += [
        "- A further %d works are tagged `focus: secondary` in the catalog: soft-tissue"
        % len(secondary),
        "  myoepithelial carcinoma, benign skin mixed tumours, and skin adnexal carcinomas",
        "  as a group.",
        "",
    ]
    year = None
    for p in primary:
        if p["year"] != year:
            year = p["year"]
            lines += ["", "## %s" % (year or "Year unknown"), ""]
        authors = p["authors"][0] + (" et al" if len(p["authors"]) > 1 else "") if p["authors"] else ""
        flags = [f for f, on in (("case report", p["is_case_report"]), ("review", p["is_review"])) if on]
        if p["language"] and p["language"] != "en":
            flags.append("language: %s" % p["language"])
        title = (p["title"] or "(no title)").rstrip(".")
        url = link(p)
        head = "[%s](%s)" % (title, url) if url else title
        detail = ". ".join(x for x in (authors, p["journal"], ", ".join(flags), access(p, have)) if x)
        lines.append("- %s. %s. `%s`" % (head, detail, p["id"]))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    log("reading list: %d primary, %d secondary -> %s" % (len(primary), len(secondary), OUT.name))


if __name__ == "__main__":
    main()
